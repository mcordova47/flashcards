// Generates the paraphrase prompt module from its committed CSV.
//
//   node tools/sync-paraphrase.mjs
//
// Refuses a row that is structurally wrong, including one naming a verb the
// table does not have: the table's spelling of an infinitive is the one every
// other file uses. Whether the model answer uses the form it claims, and
// whether it is written in deck vocabulary, is tools/check-paraphrase.mjs.

import fs from "fs"
import { loadTable } from "./verb-source.mjs"
import { CSV, TRAPS, loadPrompts } from "./paraphrase-source.mjs"

const { verbs, errors: tableErrors } = loadTable()
if (tableErrors.length) {
  console.error(`x the conjugation table is broken; run check-verbs first`)
  process.exit(1)
}

const { prompts, errors } = loadPrompts(verbs)
if (errors.length) {
  for (const e of errors) console.error(`x ${e}`)
  console.error(`${errors.length} structural problem(s) in ${CSV}; nothing written`)
  process.exit(1)
}

// Leading commas, as the deck modules write them.
const entries = prompts
  .map(p => `{ id: ${JSON.stringify(p.id)}, asked: ${JSON.stringify(p.asked)}`
          + `\n    , model: ${JSON.stringify(p.model)}`
          + `\n    , verb: ${JSON.stringify(p.verb)}, tense: ${p.tense.constructor}, person: ${p.person.constructor}`
          + `\n    , trap: ${TRAPS[p.trap]}, against: ${JSON.stringify(p.against)}\n    }`)
  .join("\n  , ")

const out = "src/Flashcards/Data/Paraphrase/Spanish.purs"
fs.mkdirSync("src/Flashcards/Data/Paraphrase", { recursive: true })
fs.writeFileSync(out, `-- | GENERATED by tools/sync-paraphrase.mjs - do not edit.
-- |
-- | Source: ${CSV} (${prompts.length} prompts).
module Flashcards.Data.Paraphrase.Spanish
  ( prompts
  )
  where

import Flashcards.Verbs.Paraphrase (Prompt, Trap(..))
import Flashcards.Verbs.Table (Person(..), Tense(..))

-- | In the corpus's order, which is the order their items are first asked in.
prompts :: Array Prompt
prompts =
  [ ${entries}
  ]
`)

console.log(`wrote ${out} (${prompts.length} prompts)`)
