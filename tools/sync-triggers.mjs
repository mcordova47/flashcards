// Generates the trigger sentence module from its committed CSVs.
//
//   node tools/sync-triggers.mjs
//
// Refuses a row that is structurally wrong. Whether it is written in deck
// vocabulary, agrees with its person and is balanced is
// tools/check-triggers.mjs.
//
// What is written is the sentence, split at its blank, with the mood, group
// and reason of its trigger. Not the form: that is the conjugation table's, and
// `Flashcards.Verbs.Mood` reads it from there.

import fs from "fs"
import { CSV, SENTENCES, GROUPS, MOODS, loadRows, loadSentences } from "./trigger-source.mjs"
import { PERSONS, loadTable } from "./verb-source.mjs"

const { verbs, errors: tableErrors } = loadTable()
const { rows, errors } = loadRows()
const { sentences, errors: sentenceErrors } = loadSentences(rows, verbs)
const all = [...tableErrors, ...errors, ...sentenceErrors]
if (all.length) {
  for (const e of all) console.error(`x ${e}`)
  console.error(`${all.length} structural problem(s) in ${CSV} or ${SENTENCES}; nothing written`)
  process.exit(1)
}

const person = Object.fromEntries(PERSONS.map(p => [p.name, p.constructor]))

// Leading commas, as the deck modules write them.
const entries = sentences
  .map(s => `{ trigger: ${JSON.stringify(s.trigger)}, mood: ${MOODS[s.bank.mood]}, group: ${GROUPS[s.bank.group].constructor}`
          + `\n    , reason: ${JSON.stringify(s.bank.reason)}`
          + `\n    , verb: ${JSON.stringify(s.verb)}, person: ${person[s.person]}`
          + `\n    , before: ${JSON.stringify(s.before)}, after: ${JSON.stringify(s.after)}`
          + `\n    }`)
  .join("\n  , ")

const out = "src/Flashcards/Data/Triggers/Spanish.purs"
fs.mkdirSync("src/Flashcards/Data/Triggers", { recursive: true })
fs.writeFileSync(out, `-- | GENERATED by tools/sync-triggers.mjs - do not edit.
-- |
-- | Source: ${SENTENCES} (${sentences.length} sentences, ${rows.length} triggers
-- | from ${CSV}). The blank's form is not here: it is the conjugation table's.
module Flashcards.Data.Triggers.Spanish
  ( sentences
  )
  where

import Flashcards.Verbs.Mood (Group(..), Mood(..), Sentence)
import Flashcards.Verbs.Table (Person(..))

-- | In the file's order, which is by verb and person. \`Mood.exercises\` is
-- | what mixes the groups within each pool.
sentences :: Array Sentence
sentences =
  [ ${entries}
  ]
`)

console.log(`wrote ${out} (${sentences.length} sentences)`)
