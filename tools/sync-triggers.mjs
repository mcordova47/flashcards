// Generates the trigger module from its committed CSV.
//
//   node tools/sync-triggers.mjs
//
// Refuses a row that is structurally wrong. Whether it is written in deck
// vocabulary, and whether the groups are wide enough, is
// tools/check-triggers.mjs.

import fs from "fs"
import { CSV, GROUPS, MOODS, loadRows } from "./trigger-source.mjs"

const { rows, errors } = loadRows()
if (errors.length) {
  for (const e of errors) console.error(`x ${e}`)
  console.error(`${errors.length} structural problem(s) in ${CSV}; nothing written`)
  process.exit(1)
}

// Leading commas, as the deck modules write them.
const entries = rows
  .map(r => `{ trigger: ${JSON.stringify(r.trigger)}, mood: ${MOODS[r.mood]}, group: ${GROUPS[r.group].constructor}`
          + `\n    , reason: ${JSON.stringify(r.reason)}\n    }`)
  .join("\n  , ")

const out = "src/Flashcards/Data/Triggers/Spanish.purs"
fs.mkdirSync("src/Flashcards/Data/Triggers", { recursive: true })
fs.writeFileSync(out, `-- | GENERATED by tools/sync-triggers.mjs - do not edit.
-- |
-- | Source: ${CSV} (${rows.length} triggers).
module Flashcards.Data.Triggers.Spanish
  ( triggers
  )
  where

import Flashcards.Verbs.Mood (Group(..), Mood(..), Trigger)

-- | In the bank's order, which is by group. \`Mood.exercises\` is what mixes
-- | the groups, so that the order here is the order a reader checks them in.
triggers :: Array Trigger
triggers =
  [ ${entries}
  ]
`)

console.log(`wrote ${out} (${rows.length} triggers)`)
