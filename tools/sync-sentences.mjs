// Generates the tense-shift sentence module from its committed CSV.
//
//   node tools/sync-sentences.mjs
//
// Refuses a sentence that is structurally wrong, including one naming a verb
// the table does not have: the table's spelling of an infinitive is the one
// every other file uses. Whether each bracketed word is the right *form*, and
// whether the rest is deck vocabulary, is tools/check-sentences.mjs.

import fs from "fs"
import { loadTable } from "./verb-source.mjs"
import { CSV, loadSentences } from "./sentence-source.mjs"

const { verbs, errors: tableErrors } = loadTable()
if (tableErrors.length) {
  console.error(`x the conjugation table is broken; run check-verbs first`)
  process.exit(1)
}

const { sentences, errors } = loadSentences(verbs)
if (errors.length) {
  for (const e of errors) console.error(`x ${e}`)
  console.error(`${errors.length} structural problem(s) in ${CSV}; nothing written`)
  process.exit(1)
}

// Leading commas, as the deck modules write them.
const entries = sentences
  .map(s => `{ before: ${JSON.stringify(s.before)}, form: ${JSON.stringify(s.form)}, after: ${JSON.stringify(s.after)}`
           + `, infinitive: "${s.infinitive}", tense: ${s.tense.constructor}, person: ${s.person.constructor} }`)
  .join("\n  , ")

const out = "src/Flashcards/Data/Sentences/Spanish.purs"
fs.mkdirSync("src/Flashcards/Data/Sentences", { recursive: true })
fs.writeFileSync(out, `-- | GENERATED by tools/sync-sentences.mjs - do not edit.
-- |
-- | Source: ${CSV} (${sentences.length} sentences).
module Flashcards.Data.Sentences.Spanish
  ( sentences
  )
  where

import Flashcards.Verbs.Shift (Sentence)
import Flashcards.Verbs.Table (Person(..), Tense(..))

-- | In the bank's order, which is the order their items are first asked in.
sentences :: Array Sentence
sentences =
  [ ${entries}
  ]
`)

console.log(`wrote ${out} (${sentences.length} sentences)`)
