// Generates the coverage recommendation module from its committed CSV.
//
//   node tools/sync-coverage.mjs
//
// The CSV is itself generated, by tools/verb-coverage.mjs, from the table and
// the deck. `npm run sync` runs that first and this second, so CI's drift
// check covers both steps: skip the first and the CSV is stale, skip the
// second and the module is. See #96.
//
// The CSV stays rather than this deriving from the rules directly: it is the
// reviewable artifact, and #27 is an argument with that file.
//
// Only the verdict is written. `Why` is most of the file and is prose for a
// person reading it; `Form` and `Deviates` are already in the verbs module,
// and `Rank` and `Recovers` are inputs to the verdict rather than part of it.
//
// Refuses a row that is structurally wrong, and a CSV whose cells are not
// exactly the table's - the second is what running this without
// verb-coverage after a change to the table looks like.

import fs from "fs"
import { TENSES, PERSONS, loadTable } from "./verb-source.mjs"
import { parseCsv } from "./deck-source.mjs"

const CSV = "data/es-verb-coverage.csv"
const HEADER = ["Infinitive", "Rank", "Tense", "Person", "Form", "Deviates", "Recovers", "Recommend", "Why"]
const RECOMMEND = { drill: "Drill", later: "Later", skip: "Skip" }

const tense = Object.fromEntries(TENSES.map(t => [t.name, t.constructor]))
const person = Object.fromEntries(PERSONS.map(p => [p.name, p.constructor]))

const fail = errors => {
  for (const e of errors) console.error(`x ${e}`)
  console.error(`${errors.length} structural problem(s) in ${CSV}; nothing written`)
  process.exit(1)
}

const table = loadTable()
if (table.errors.length) fail(table.errors)

const [header, ...body] = parseCsv(fs.readFileSync(CSV, "utf-8"))
if (HEADER.some((c, i) => header[i] !== c) || header.length !== HEADER.length) {
  fail([`expected the header ${HEADER.join(",")}, got ${header.join(",")}`])
}

const errors = []
const rows = []
const seen = new Map()
body.forEach((cells, i) => {
  const line = i + 2
  if (cells.length !== HEADER.length) {
    errors.push(`line ${line} has ${cells.length} fields, not ${HEADER.length}`)
    return
  }
  const [infinitive, , t, p, , , , recommend] = cells
  if (!tense[t]) errors.push(`line ${line}: ${JSON.stringify(t)} is not one of ${Object.keys(tense).join(", ")}`)
  if (!person[p]) errors.push(`line ${line}: ${JSON.stringify(p)} is not one of ${Object.keys(person).join(", ")}`)
  if (!RECOMMEND[recommend]) errors.push(`line ${line}: ${JSON.stringify(recommend)} is not one of ${Object.keys(RECOMMEND).join(", ")}`)
  const key = `${infinitive}.${t}.${p}`
  if (seen.has(key)) errors.push(`line ${line}: ${infinitive} ${t} ${p} is already on line ${seen.get(key)}`)
  seen.set(key, line)
  rows.push({ infinitive, tense: t, person: p, recommend })
})

// Every cell of the table, and nothing else.
const expected = table.verbs.flatMap(v => TENSES.flatMap(t => PERSONS.map(p => `${v.infinitive}.${t.name}.${p.name}`)))
const missing = expected.filter(k => !seen.has(k))
const extra = [...seen.keys()].filter(k => !expected.includes(k))
if (missing.length) errors.push(`${missing.length} cell(s) of the table have no recommendation, starting ${missing[0]}; run \`npm run verb-coverage\``)
if (extra.length) errors.push(`${extra.length} recommendation(s) for cells the table does not have, starting ${extra[0]}; run \`npm run verb-coverage\``)
// And in its order, which the module promises.
const moved = rows.findIndex((r, i) => `${r.infinitive}.${r.tense}.${r.person}` !== expected[i])
if (!missing.length && !extra.length && moved !== -1) errors.push(`line ${moved + 2} is out of the table's order; run \`npm run verb-coverage\``)

if (errors.length) fail(errors)

// Leading commas, as the deck modules write them.
const entries = rows
  .map(r => `{ infinitive: "${r.infinitive}", tense: ${tense[r.tense]}`
           + `, person: ${person[r.person]}, recommend: ${RECOMMEND[r.recommend]} }`)
  .join("\n  , ")

const tally = Object.keys(RECOMMEND).map(k => `${rows.filter(r => r.recommend === k).length} ${k}`).join(", ")

const out = "src/Flashcards/Data/Coverage/Spanish.purs"
fs.mkdirSync("src/Flashcards/Data/Coverage", { recursive: true })
fs.writeFileSync(out, `-- | GENERATED by tools/sync-coverage.mjs - do not edit.
-- |
-- | Source: ${CSV} (${rows.length} cells: ${tally}),
-- | which is generated in turn by tools/verb-coverage.mjs.
module Flashcards.Data.Coverage.Spanish
  ( coverage
  )
  where

import Flashcards.Verbs.Coverage (Recommend(..), Verdict)
import Flashcards.Verbs.Table (Person(..), Tense(..))

-- | One entry per cell of the conjugation table, in its order: grouped by
-- | verb, then tense, then person.
coverage :: Array Verdict
coverage =
  [ ${entries}
  ]
`)

console.log(`wrote ${out} (${rows.length} cells)`)
